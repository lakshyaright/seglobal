import React from 'react';
import { SAMPLE_PROJECTS } from '../sampleCodes.ts';
import { SampleProject } from '../types.ts';
import { Sparkles, ArrowRight, Check } from 'lucide-react';

interface SamplePickerProps {
  onSelectSample: (sample: SampleProject) => void;
  activeSampleId: string | null;
}

export const SamplePicker: React.FC<SamplePickerProps> = ({
  onSelectSample,
  activeSampleId,
}) => {
  return (
    <div className="flex-1 overflow-auto bg-slate-950 p-6 text-slate-100">
      <div className="max-w-5xl mx-auto space-y-6">
        <div>
          <h1 className="text-xl font-bold tracking-tight text-white flex items-center gap-2">
            <Sparkles className="w-5 h-5 text-emerald-400" />
            <span>Preloaded Gemini Code Gallery</span>
          </h1>
          <p className="text-xs text-slate-400 mt-1">
            Explore ready-to-run interactive apps generated by Gemini. Click any demo to load it into the live sandboxed runner.
          </p>
        </div>

        <div className="grid grid-cols-1 md:grid-cols-2 gap-4">
          {SAMPLE_PROJECTS.map((sample) => {
            const isCurrent = activeSampleId === sample.id;
            return (
              <div
                key={sample.id}
                className={`p-5 rounded-lg border transition-all flex flex-col justify-between ${
                  isCurrent
                    ? 'bg-slate-900 border-emerald-500/50 ring-1 ring-emerald-500/30'
                    : 'bg-slate-900/60 border-slate-800 hover:border-slate-700'
                }`}
              >
                <div className="space-y-2">
                  <div className="flex items-center justify-between text-xs text-slate-400">
                    <span className="text-emerald-400 font-medium">{sample.category}</span>
                    <span className="font-mono text-[11px]">{sample.filename}</span>
                  </div>
                  <h3 className="text-base font-semibold text-white">{sample.title}</h3>
                  <p className="text-xs text-slate-400 leading-relaxed">{sample.description}</p>
                </div>

                <div className="pt-4 border-t border-slate-800/80 mt-4 flex items-center justify-between">
                  <div className="flex items-center gap-2 text-xs text-slate-500">
                    <span>{sample.tags[0]}</span>
                    <span>·</span>
                    <span>{sample.tags[1]}</span>
                  </div>

                  <button
                    onClick={() => onSelectSample(sample)}
                    className={`px-3.5 py-1.5 text-xs font-semibold rounded-md transition-colors flex items-center gap-1.5 cursor-pointer ${
                      isCurrent
                        ? 'bg-emerald-500/20 text-emerald-300 border border-emerald-500/30'
                        : 'bg-slate-800 hover:bg-slate-700 text-slate-200 border border-slate-700'
                    }`}
                  >
                    {isCurrent ? (
                      <>
                        <Check className="w-3.5 h-3.5 text-emerald-400" />
                        <span>Active in Runner</span>
                      </>
                    ) : (
                      <>
                        <span>Load Project</span>
                        <ArrowRight className="w-3.5 h-3.5" />
                      </>
                    )}
                  </button>
                </div>
              </div>
            );
          })}
        </div>
      </div>
    </div>
  );
};
